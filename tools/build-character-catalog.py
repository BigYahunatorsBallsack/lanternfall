def pascal(text: str) -> str:
    return "".join(word[:1].upper() + word[1:] for word in re.split(r"[^A-Za-z0-9]+", text) if word)


def normalized(text: str) -> str:
    return re.sub(r"[^a-z0-9]", "", text.lower())


def slug_of(original_id: str) -> str:
    return re.sub(r"_\d+$", "", original_id.removeprefix("weapon_").removeprefix("item_"))


def add(stats: dict[str, float], key: str, amount: float):
    stats[key] = stats.get(key, 0) + amount


def parameter(name: str, value: Any):
    row = {"name": name}
    if isinstance(value, bool):
        row["booleanValue"] = value
    elif isinstance(value, (int, float)):
        row["numberValue"] = value
    elif isinstance(value, str):
        row["stringValue"] = value
    elif isinstance(value, dict) and "resource" in value:
        row["resource"] = value["resource"]
    elif isinstance(value, dict) and "variantType" in value:
        row["variantType"] = value["variantType"]
        row["numberValues"] = value["values"]
    elif isinstance(value, list):
        if all(isinstance(v, str) for v in value):
            row["stringValues"] = value
        elif all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value):
            row["numberValues"] = value
        elif all(isinstance(v, dict) and "resource" in v for v in value):
            row["resources"] = [v["resource"] for v in value]
        else:
            raise ValueError(f"Unsupported rule parameter {name}: {value}")
    else:
        raise ValueError(f"Unsupported rule parameter {name}: {value}")
    return row


def source_effect(source, resource):
    p = resource["properties"]
    keys = {"key", "custom_key", "value", "storage_method", "effect_sign", "text_key", "tracking_text", "tracking_key", "base_smoke_amount", "outline_color"}
    return {
        "sourceKey": p.get("key", ""), "customKey": p.get("custom_key", ""), "amount": p.get("value", 0),
        "source": source, "effectType": resource["effectType"], "storageMethod": p.get("storage_method", 0),
        "textKey": p.get("text_key", ""),
        "parameters": [parameter(k, v) for k, v in p.items() if k not in keys],
    }


def compile_catalog(source, weapons, items):
    weapon_map = {normalized(w["name"]): w["id"] for w in weapons}
    item_map = {normalized(i["name"]): i["id"] for i in items}
    unknown_weapons, unknown_items = set(), set()

    def equipment(row, kind):
        slug = slug_of(row["id"])
        mapping = weapon_map if kind == "Weapon" else item_map
        name = row["nameKey"].removeprefix("WEAPON_").removeprefix("ITEM_")
        existing = mapping.get(normalized(name)) or mapping.get(normalized(slug))
        if kind == "Weapon":
            existing = WEAPON_ALIASES.get(slug, existing)
        if not existing:
            (unknown_weapons if kind == "Weapon" else unknown_items).add(slug)
        result = {"id": existing or pascal(slug), "tier": row["tier"] + 1,
                  "originalId": row["id"], "source": row["source"]}
        if row.get("cursed"):
            result["cursed"] = True
        return result

    result = {}
    for char in source["characters"]:
        slug = char["slug"]
        rules = char["selectionRules"]
        choices = [equipment(w, "Weapon") for w in char["startingWeapons"]]
        item_choices = [equipment(i, "Item") for i in char["startingItems"]]
        grants = [(g, equipment(g, g["kind"])) for g in char["guaranteedEquipment"]]
        row = {
            "id": STABLE_IDS.get(slug, pascal(slug)), "originalId": char["id"],
            "displayName": DISPLAY_NAMES.get(slug, slug.replace("_", " ").title()),
            "source": char["source"], "sourceMd5": char["sourceMd5"], "contentSet": char["contentSet"],
            "free": rules["unlocked_by_default"], "stats": {}, "gainMultipliers": {}, "perLevel": {},
            "perWave": {}, "conversions": [], "perWeapon": {}, "perDistinctWeapon": {},
            "perTierWeapon": {}, "weaponClassStats": {}, "weaponKindStats": {}, "stationaryStats": {},
            "startWeapon": choices[0]["id"] if choices else "", "startWeapons": [w["id"] for w in choices],
            "startChoices": choices, "extraWeapons": [], "extraWeaponTiers": {}, "extraWeaponChoices": [],
            "startItems": [], "startItemChoices": item_choices, "cursedStartItems": [],
            "wantedTags": [STATS.get(tag, tag) for tag in rules.get("wanted_tags", [])],
            "sourceWantedTags": rules.get("wanted_tags", []), "tags": rules.get("tags", []),
            "bannedItemGroups": rules.get("banned_item_groups", []), "bannedItems": rules.get("banned_items", []),
            "bannedUpgrades": rules.get("banned_upgrades", []), "bannedMechaStats": rules.get("banned_meca_stats", []),
            "requiredItemSet": rules.get("required_item_set", ""), "minimumDifficulty": rules.get("minimum_difficulty", 0),
            "sourceEffects": [], "remainingRules": [],
        }
        for grant, eq in grants:
            for _ in range(grant["count"]):
                if grant["kind"] == "Weapon":
                    row["extraWeapons"].append(eq["id"])
                    row["extraWeaponTiers"][eq["id"]] = eq["tier"]
                    row["extraWeaponChoices"].append(eq)
                else:
                    row["startItems"].append(eq["id"])
                    if grant["cursed"]:
                        row["cursedStartItems"].append(eq["id"])
        for effect in char["effects"]:
            resource = source["resources"][effect["resource"]]
            p = resource["properties"]
            meta = source_effect(effect["resource"], resource)
            row["sourceEffects"].append(meta)
            kind = resource["effectType"].rsplit("/", 1)[-1]
            key, custom, amount, storage = meta["sourceKey"], meta["customKey"], meta["amount"], meta["storageMethod"]
            stat = STATS.get(key)
            handled = True
            if kind == "stat_gains_modification_effect.gd":
                for native in p["stats_modified"]:
                    target = STATS.get(native)
                    if target is None:
                        raise ValueError(f"Unknown stat-gain target: {native}")
                    row["gainMultipliers"][target] = round(1 + amount / 100, 12)
            elif kind == "gain_stat_for_every_stat_effect.gd" and stat:
                native = p["stat_scaled"]
                source_id = STATS.get(native) or COUNTS.get(native)
                if native.startswith("item_"):
                    source_id = "item:" + (item_map.get(normalized(native.removeprefix("item_"))) or pascal(native.removeprefix("item_")))
                if source_id is None:
                    raise ValueError(f"Unknown conversion count {native}")
                row["conversions"].append({
                    "source": source_id, "sourceKind": "Stat" if native in STATS else "Count", "target": stat,
                    "per": p["nb_stat_scaled"], "amount": amount, "permanentOnly": p["perm_stats_only"],
                })
            elif kind == "class_bonus_effect.gd":
                class_id = SETS[p["set_id"]]
                target = CLASS_STATS[p["stat_name"]]
                add(row["weaponClassStats"].setdefault(class_id, {}), target, amount)
            elif kind == "weapon_type_bonus_effect.gd":
                weapon_kind = {0: "Melee", 1: "Ranged"}[p["weapon_type"]]
                add(row["weaponKindStats"].setdefault(weapon_kind, {}), CLASS_STATS[p["stat_name"]], amount)
            elif kind == "effect.gd" and custom in ("starting_item", "cursed_starting_item", "starting_weapon"):
                pass  # Resolved above, including original item tiers and guaranteed counts.
            elif kind == "effect.gd" and stat and custom in ("stats_on_level_up", "stats_end_of_wave") and storage == 1:
                add(row["perLevel"] if custom == "stats_on_level_up" else row["perWave"], stat, amount)
            elif kind == "effect.gd" and stat and custom == "additional_weapon_effects" and storage == 1:
                add(row["perWeapon"], stat, amount)
            elif kind == "effect.gd" and stat and custom == "unique_weapon_effects" and storage == 1:
                add(row["perDistinctWeapon"], stat, amount)
            elif kind == "effect.gd" and stat and custom in ("tier_i_weapon_effects", "tier_iv_weapon_effects") and storage == 1:
                add(row["perTierWeapon"].setdefault(1 if custom == "tier_i_weapon_effects" else 4, {}), stat, amount)
            elif kind == "effect.gd" and stat and not custom and storage == 0:
                # Soldier can only attack stationary; its combat bonuses are consumed by the stationary policy.
                target = row["stationaryStats"] if slug == "soldier" and stat in ("damage", "attackSpeed") else row["stats"]
                add(target, stat, amount)
            elif kind == "effect.gd" and key == "dodge_cap" and not custom and storage == 2:
                row["stats"]["dodgeCap"] = amount
            elif kind == "effect.gd" and key == "can_attack_while_moving" and storage == 2:
                row["canAttackWhileMoving"] = amount != 0
            elif kind == "effect.gd" and key == "weapon_slot" and storage in (0, 2):
                row["maxWeapons"] = amount if storage == 2 else 6 + amount
            elif kind == "effect.gd" and key in ("min_weapon_tier", "max_weapon_tier"):
                row["minWeaponTier" if key == "min_weapon_tier" else "maxWeaponTier"] = amount + 1
            elif kind == "effect.gd" and key in ("max_melee_weapons", "max_ranged_weapons"):
                row.setdefault("kindLimits", {})["Melee" if key == "max_melee_weapons" else "Ranged"] = amount
            elif kind == "effect.gd" and key in ("no_melee_weapons", "no_ranged_weapons"):
                row["weaponKind"] = "Ranged" if key == "no_melee_weapons" else "Melee"
            elif kind == "effect.gd" and key in ("no_heal", "die_in_one_hit", "no_cure_between_wave", "no_duplicate_weapons", "all_weapons_count_for_sets"):
                row[{
                    "no_heal": "noHeal", "die_in_one_hit": "oneHit", "no_cure_between_wave": "noWaveHeal",
                    "no_duplicate_weapons": "noDuplicateWeapons", "all_weapons_count_for_sets": "allWeaponsForSets",
                }[key]] = amount != 0
            elif kind == "effect.gd" and key == "weapon_set_bonus":
                row["setCountBonus"] = amount
            elif kind == "effect.gd" and key == "weapon_slot_upgrades":
                row["baseWeaponSlots"], row["slotsPerLevel"], row["maxWeaponSlots"] = 1, 1, amount
            else:
                handled = False
            if not handled:
                row["remainingRules"].append(meta)
        if row.get("baseWeaponSlots"):
            # maxWeapons is the eventual technical capacity; baseWeaponSlots is the starting capacity.
            row["baseWeaponSlots"] = row.get("maxWeapons", row["baseWeaponSlots"])
            row["maxWeapons"] = row["maxWeaponSlots"]
        assert row["id"] not in result
        result[row["id"]] = row
    assert len(result) == 74
    for slug, stable in STABLE_IDS.items():
        assert result[stable]["originalId"] == "character_" + slug
    assert result["WellRounded"]["stats"]["maxHp"] == 5
    assert result["MarbleHost"]["stats"]["fruitHeal"] == 3
    assert result["CandleScholar"]["perLevel"]["maxHp"] == -2
    assert result["Baby"]["baseWeaponSlots"] == 1 and result["Baby"]["maxWeapons"] == 24
    assert result["Bull"]["maxWeapons"] == 0
    return result, unknown_weapons, unknown_items


def luau(value, indent=0):
    prefix = "\t" * indent
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (int, float)):
        return str(value) if isinstance(value, int) else format(value, ".15g")
    if isinstance(value, (list, dict)):
        if not value:
            return "{}"
        rows = []
        if isinstance(value, list):
            for entry in value:
                rows.append(prefix + "\t" + luau(entry, indent + 1) + ",")
        else:
            for key, entry in value.items():
                lhs = str(key) if isinstance(key, str) and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key) else "[" + luau(key) + "]"
                rows.append(prefix + "\t" + lhs + " = " + luau(entry, indent + 1) + ",")
        return "{\n" + "\n".join(rows) + "\n" + prefix + "}"
    raise ValueError(f"Cannot serialize {value!r}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "docs/characters/source.json")
    parser.add_argument("--output", type=Path, default=ROOT / "src/shared/Config/CharacterCatalog.luau")
    parser.add_argument("--check", action="store_true", help="Verify generated output without writing")
    args = parser.parse_args()
    source = json.loads(args.source.read_text(encoding="utf-8"))
    weapons = json.loads((ROOT / "assets/weapons/brotato-base/catalog.json").read_text(encoding="utf-8"))["weapons"]
    items = json.loads((ROOT / "docs/item-parity/catalog.json").read_text(encoding="utf-8"))["items"]
    catalog, unknown_weapons, unknown_items = compile_catalog(source, weapons, items)
    generated = HEADER + luau(catalog) + "\n\nreturn table.freeze(Catalog)\n"
    if args.check:
        assert args.output.read_text(encoding="utf-8") == generated, "CharacterCatalog is stale; regenerate it"
    else:
        args.output.write_text(generated, encoding="utf-8", newline="\n")
    counts = Counter(c["contentSet"] for c in catalog.values())
    remaining = sum(len(c["remainingRules"]) for c in catalog.values())
    print(f"74 characters compiled; sets={dict(counts)}; {remaining} explicit remaining policy rules")
    print("Missing weapons (native slugs): " + ", ".join(sorted(unknown_weapons)))
    print("Missing items (native slugs): " + ", ".join(sorted(unknown_items)))


if __name__ == "__main__":
    main()
