"""Compile neutral native aiming facts for the existing ranged weapon roster."""
import argparse
import importlib.util
import json
from pathlib import Path
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
FACTS = ROOT / "docs/characters/ranged-source.json"
OUTPUT = ROOT / "src/shared/Config/CharacterRangedData.luau"


def refresh():
    spec = importlib.util.spec_from_file_location("source", ROOT / "tools/character-source.py")
    source = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(source)
    pck = source.Pck()
    normalize = lambda text: "".join(c for c in text.lower() if c.isalnum())
    roster = json.loads((ROOT / "assets/weapons/brotato-base/catalog.json").read_text())['weapons']
    mapping = {normalize(w['name']): w['id'] for w in roster if w['kind'] == 'Ranged'}
    result = {}
    for path in pck.entries:
        if not path.endswith('.tres') or ('/weapons/ranged/' not in path or '_data' not in path):
            continue
        data = pck.resource(path)['properties']
        if 'weapon_id' not in data or data.get('is_meca') or data.get('is_mutant'):
            continue
        ident = mapping.get(normalize(data['name'].removeprefix('WEAPON_')))
        if ident is None:
            continue
        stats_path = data['stats']['resource']
        stats = pck.resource(stats_path)['properties']
        result.setdefault(ident, []).append({
            'tier': data['tier'] + 1, 'source': path, 'sourceMd5': pck.entries[path]['md5'],
            'statsSource': stats_path, 'statsMd5': pck.entries[stats_path]['md5'],
            'accuracy': stats['accuracy'], 'spread': stats['projectile_spread'],
            'count': stats['nb_projectiles'],
        })
    assert set(result) == set(mapping.values()), set(mapping.values()) - set(result)
    for rows in result.values():
        rows.sort(key=lambda row: row['tier'])
        assert len({row['tier'] for row in rows}) == len(rows)
    FACTS.write_text(json.dumps({'version': '1.2.0.1', 'steamBuild': 26406319,
                                'weapons': result}, indent=2) + '\n', encoding='utf-8')


def generate():
    result = ['--!strict', '-- Native aiming facts for existing weapons; NativeRangedStats reads this generated table.',
              '-- Generated by tools/build-character-ranged.py from the neutral ranged-source.json snapshot.', 'return {']
    for ident, rows in sorted(json.loads(FACTS.read_text(encoding='utf-8'))['weapons'].items()):
        result.append(f'\t{ident} = {{')
        by_tier = {row['tier']: row for row in rows}
        for tier in range(1, 5):
            row = by_tier[max(tier, rows[0]['tier'])]
            result.append(f'\t\t{{ accuracy = {row["accuracy"]}, spread = {row["spread"]}, count = {row["count"]} }},')
        result.append('\t},')
    return '\n'.join(result + ['}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--refresh', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.refresh:
        refresh()
    generated = generate()
    if args.check:
        assert OUTPUT.read_text(encoding='utf-8') == generated, 'Ranged data is stale'
    else:
        OUTPUT.write_text(generated, encoding='utf-8')

