"""Builds tests/helpers/RobloxApi.luau from a Roblox Full-API-Dump.json.

Usage: python3 tools/api/generate.py <Full-API-Dump.json>
Dump source: https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json
Only classes whose name appears as a string in src/ are written, so the file stays small.
The test mock (tests/helpers/RobloxMock.luau) rejects writes to properties that are not on this list.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]


def main() -> None:
    dump = json.loads(pathlib.Path(sys.argv[1]).read_text())
    classes = {c["Name"]: c for c in dump["Classes"]}
    used = set()
    for path in (ROOT / "src").rglob("*.luau"):
        used.update(re.findall(r'"([A-Z][A-Za-z0-9]+)"', path.read_text()))
    wanted = set()
    for name in used & classes.keys():
        while name and name in classes and name != "<<<ROOT>>>":
            wanted.add(name)
            name = classes[name].get("Superclass")
    lines = [
        "-- Generated by tools/api/generate.py from the Roblox API dump. Do not edit by hand.",
        "-- Writable properties (and callbacks) per class, plus the superclass; used by RobloxMock to reject",
        "-- property names Roblox does not have.",
        "return {",
    ]
    for name in sorted(wanted):
        cls = classes[name]
        props = []
        for member in cls["Members"]:
            if member["MemberType"] not in ("Property", "Callback"):
                continue
            tags = member.get("Tags", [])
            if "ReadOnly" in tags or "NotScriptable" in tags:
                continue
            security = member.get("Security", "None")
            if isinstance(security, dict):
                security = security.get("Write", "None")
            if security not in ("None", "PluginSecurity"):
                continue
            props.append(member["Name"])
        superclass = cls.get("Superclass")
        sup = f'"{superclass}"' if superclass and superclass in wanted else "nil"
        joined = ", ".join(f'"{p}"' for p in sorted(set(props)))
        lines.append(f"\t{name} = {{ super = {sup}, props = {{ {joined} }} }},")
    lines.append("}")
    out = ROOT / "tests" / "helpers" / "RobloxApi.luau"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(wanted)} classes to {out}")


if __name__ == "__main__":
    main()
