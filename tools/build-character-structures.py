"""Compile checked-in stable native structure facts; original scripts and archives never enter output."""
import json, subprocess, importlib.util, sys
sys.dont_write_bytecode = True
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
s=importlib.util.spec_from_file_location('cat',ROOT/'tools/build-character-catalog.py');cat=importlib.util.module_from_spec(s);s.loader.exec_module(cat)
facts=json.loads((ROOT/'docs/characters/structure-source.json').read_text(encoding='utf-8'))
out={}
for row in facts['structures']:
 st=row['stats']; ident=row['id']; scale={cat.STATS[k]:v for k,v in st['scaling_stats']}
 d={'native':True,'nativeProjectile':not st['is_healing'] and ident!='RuneMine','damage':st['damage'],'engineering':scale.get('engineering',0),'interval':st['cooldown']/60,'cooldownFrames':st['cooldown'],'range':st['max_range']*.1,'projectileSpeed':st['projectile_speed']*.1,'pierce':st['piercing'],'pierceFalloff':st['piercing_dmg_reduction'],'critChance':st['crit_chance'],'critDamage':st['crit_damage'],'spawnCooldown':row['spawnCooldown'],'nativeAccuracy':st['accuracy'],'nativeSpread':st['projectile_spread'],'count':st['nb_projectiles']}
 if ident in ['RuneMine','DartTrap']:
  d.update(mode='Mine' if ident=='RuneMine' else 'Trap',range=facts['geometry']['mineTriggerRadiusPoints' if ident=='RuneMine' else 'trapTriggerRadiusPoints']*.1,triggerOffsetZ=facts['geometry']['triggerOffsetPoints']*.1)
 if 'boostMode' in row:d.update(boostMode=row['boostMode'])
 if 'animationSpeed' in row:d.update(animationSpeed=row['animationSpeed'])
 if ident=='DartTrap':d.update(rays=facts['geometry']['dartCount'],shotRange=st['max_range']*.1)
 for e in row['effects']:
  if e.get('scale'):d['radius']=facts['geometry']['explosionRadiusPoints']*.1*e['scale']
  if 'burn' in e:
   b=e['burn'];bs={cat.STATS[k]:v for k,v in b['scaling_stats']};d.update(burnBase=b['damage'],ticks=b['duration'],burnEngineering=bs.get('engineering',0),burnElemental=bs.get('elementalDamage',0))
 out[ident]=d
path=ROOT/'src/shared/Config/CharacterStructureData.luau'
path.write_text('--!strict\n-- Stable native structure extensions; Structures merges these verified values.\n-- Generated by tools/build-character-structures.py from structure-source.json.\nreturn '+cat.luau(out)+'\n',encoding='utf-8')
subprocess.run(['stylua',str(path)],check=True)
